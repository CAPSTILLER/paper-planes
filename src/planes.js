// Plane data. Paper is 85 x 110 (US Letter in tenths of an inch). Top = nose.
const C = 42.5
const V = (a, b, s, o = {}) => ({ kind: 'fold', type: 'valley', a, b, s, ...o })
const M = (a, b, s, o = {}) => ({ kind: 'fold', type: 'mountain', a, b, s, ...o })
const CR = (a, b, s, o = {}) => ({ kind: 'fold', type: 'valley', a, b, s, crease: true, ...o })
const FLIP = (axis = C) => ({ kind: 'flip', axis })
const mx = (p) => [127.5 - p[0], p[1]] // mirror used after flipping a half-folded plane
const foldTo = (p, q, o = {}) => {
  const m = [(p[0] + q[0]) / 2, (p[1] + q[1]) / 2]
  const d = [q[0] - p[0], q[1] - p[1]]
  return V(m, [m[0] - d[1], m[1] + d[0]], p, o)
}
